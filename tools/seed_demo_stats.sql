-- ---------------------------- 状态校正（必须在 wuliu 插入之后） ----------------------------
-- 背景：触发器 wuliu_insert 会在插入物流记录时把订单 checked 强制置 1（"已派发"）。
-- 因此这里按 wuliu.ended 把演示数据的状态一次性校正为：
--   ended = 1（已送达） -> checked = 2
--   ended = 0（在途）   -> checked = 1
--   无物流记录          -> checked = 0（未派发，保持原值即可，这里也显式写一次）
UPDATE `oorder` o
SET o.`checked` = CASE
        WHEN EXISTS (SELECT 1 FROM `wuliu` w WHERE w.`order_id` = o.`order_id` AND w.`ended` = 1) THEN 2
        WHEN EXISTS (SELECT 1 FROM `wuliu` w WHERE w.`order_id` = o.`order_id` AND w.`ended` = 0) THEN 1
        ELSE 0
    END
WHERE o.`order_id` >= @seed_min_order_id;

